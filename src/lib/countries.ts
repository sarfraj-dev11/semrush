/**
 * Returns the flag emoji for a 2-letter ISO country code.
 * Falls back to 🌐 for Worldwide ("WW") or invalid codes.
 */
export function getCountryFlag(countryCode?: string | null): string {
  if (!countryCode || countryCode.toUpperCase() === "WW") return "🌐";
  const code = countryCode.toUpperCase();
  if (code.length !== 2) return "🌐";
  const first = code.charCodeAt(0) - 65 + 0x1f1e6;
  const second = code.charCodeAt(1) - 65 + 0x1f1e6;
  if (first < 0x1f1e6 || first > 0x1f1ff || second < 0x1f1e6 || second > 0x1f1ff) {
    return "🌐";
  }
  return String.fromCodePoint(first, second);
}

/**
 * Returns the flag image URL from FlagCDN for any 2-letter ISO country code.
 * Falls back to UN flag for Worldwide ("WW").
 */
export function getCountryFlagUrl(countryCode?: string | null): string {
  if (!countryCode || countryCode.toUpperCase() === "WW") {
    return "https://flagcdn.com/w40/un.png";
  }
  return `https://flagcdn.com/w40/${countryCode.toLowerCase()}.png`;
}

